public class Student{
    private String name; 
    private int age;
    //getter method
    public String getName(){
        return this.name;
    }
    public int getAge(){
        return this.age;
    }
    // setter method
    public void setName(String name){
        this.name = name;
    }
    public void setAge(int age){
        this.age = age;
    }
}